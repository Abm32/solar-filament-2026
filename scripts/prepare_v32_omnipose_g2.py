"""Stage the frozen V32 G2 numerical-overfit gate as a private Kaggle kernel.

This stages but never launches. The generated wrapper installs pinned decoder
requirements, obtains the exact Omnipose commit and public ImageNet backbone,
verifies all hashes, and runs at most 2,000 optimizer steps. It has no audit,
test, export, CSV, or submission path.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

MODULE = "train_v32_omnipose_overfit"
SLUG = "solar-filament-v32-omnipose-g2-fix1"
TITLE = "Solar Filament V32 Omnipose G2 Fix1"
UPSTREAM_COMMIT = "21e4d0199cc03662669c150f6151e3365dc201fd"
UPSTREAM_CORE_SHA256 = "300f4cf24ad5256c35726442e024efa9e98cb27b200a3f36a6da01e3839ab332"
BACKBONE_URL = "https://download.pytorch.org/models/resnet50-0676ba61.pth"
BACKBONE_SHA256 = "0676ba61b6795bbe1773cffd859882e5e297624d384b6993f7c9e683e722fb8a"
ANNOTATION_SHA256 = "5da9e92b5a1a1947fd5d57adb6688269625c48ec1ef884daf2a01618c9ed54a1"
MAX_STEPS = 2000
# Exact runtime additions. Torch/torchvision/OpenCV/pycocotools come from the
# pinned Kaggle image so their CUDA ABI remains matched.
PACKAGES = (
    "numba==0.61.2", "edt==3.1.2", "scikit-image==0.25.2",
    "ncolor==1.2.1", "scikit-learn==1.6.1", "mahotas==1.4.18",
    "mgen==1.2.1", "igraph==0.11.9", "torchvf==0.1.4",
    "fastremap==1.20.0", "tifffile==2025.6.11", "networkx==3.4.2",
)


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def stage(root: Path, output: Path) -> Path:
    root, output = Path(root), Path(output)
    source_path = root / "scripts" / f"{MODULE}.py"
    source = source_path.read_text()
    compile(source, str(source_path), "exec")
    source_hash = hashlib.sha256(source.encode()).hexdigest()
    annotations = (
        root / "data/raw/filament-segmentation-2026/MAGFiLO_1.0_Kaggle_2026/"
        "train/MAGFiLO_1.0_Annotations_kaggle2026_train.json"
    )
    if sha256(annotations) != ANNOTATION_SHA256:
        raise RuntimeError("canonical V32 annotation identity changed")

    wrapper = f'''# Generated by scripts/prepare_v32_omnipose_g2.py; do not edit.
import hashlib
import os
from pathlib import Path
import subprocess
import sys
import urllib.request

SOURCE = {source!r}
SOURCE_SHA256 = {source_hash!r}
PACKAGES = {PACKAGES!r}
COMMIT = {UPSTREAM_COMMIT!r}
CORE_SHA256 = {UPSTREAM_CORE_SHA256!r}
BACKBONE_URL = {BACKBONE_URL!r}
BACKBONE_SHA256 = {BACKBONE_SHA256!r}
ANNOTATION_SHA256 = {ANNOTATION_SHA256!r}
MAX_STEPS = {MAX_STEPS}


def digest(path):
    value = hashlib.sha256()
    with open(path, "rb") as stream:
        for block in iter(lambda: stream.read(1 << 20), b""):
            value.update(block)
    return value.hexdigest()


def checked(command, **kwargs):
    print("RUN", " ".join(map(str, command)), flush=True)
    subprocess.run(command, check=True, **kwargs)


def competition_root():
    candidates = (
        Path("/kaggle/input/competitions/filament-segmentation-2026/MAGFiLO_1.0_Kaggle_2026"),
        Path("/kaggle/input/filament-segmentation-2026/MAGFiLO_1.0_Kaggle_2026"),
    )
    for candidate in candidates:
        annotation = candidate / "train/MAGFiLO_1.0_Annotations_kaggle2026_train.json"
        if annotation.is_file() and digest(annotation) == ANNOTATION_SHA256:
            return candidate
    raise RuntimeError("canonical competition training data not found")


if __name__ == "__main__":
    if hashlib.sha256(SOURCE.encode()).hexdigest() != SOURCE_SHA256:
        raise RuntimeError("bundled V32 G2 source changed")
    work = Path("/kaggle/working/v32_g2_runtime")
    work.mkdir(parents=True, exist_ok=True)
    checked([sys.executable, "-m", "pip", "install", "--quiet", "--no-input", *PACKAGES])
    upstream = work / "omnipose-v106"
    checked(["git", "clone", "--quiet", "https://github.com/kevinjohncutler/omnipose.git", str(upstream)])
    checked(["git", "-C", str(upstream), "checkout", "--quiet", COMMIT])
    if digest(upstream / "omnipose/core.py") != CORE_SHA256:
        raise RuntimeError("pinned Omnipose core changed")
    backbone = work / "resnet50-0676ba61.pth"
    urllib.request.urlretrieve(BACKBONE_URL, backbone)
    if digest(backbone) != BACKBONE_SHA256:
        raise RuntimeError("public ImageNet backbone identity changed")
    runner = work / "{MODULE}.py"
    runner.write_text(SOURCE)
    root = competition_root()
    env = os.environ.copy()
    env["CUBLAS_WORKSPACE_CONFIG"] = ":4096:8"
    checked([
        sys.executable, str(runner),
        "--annotations", str(root / "train/MAGFiLO_1.0_Annotations_kaggle2026_train.json"),
        "--images", str(root / "train/train_images"),
        "--upstream", str(upstream),
        "--backbone", str(backbone),
        "--output", "/kaggle/working/v32_g2_result.json",
        "--steps", str(MAX_STEPS), "--device", "0",
    ], env=env)
'''
    compile(wrapper, f"{MODULE}_kernel.py", "exec")
    output.mkdir(parents=True, exist_ok=True)
    code_file = output / f"{MODULE}_kernel.py"
    code_file.write_text(wrapper)

    metadata = {
        "id": f"abhimanyu122/{SLUG}", "title": TITLE,
        "code_file": code_file.name, "language": "python", "kernel_type": "script",
        "is_private": "true", "enable_gpu": "true", "enable_tpu": "false",
        "enable_internet": "true", "machine_shape": "NvidiaTeslaT4",
        "dataset_sources": [], "competition_sources": ["filament-segmentation-2026"],
        "kernel_sources": [], "model_sources": [],
    }
    (output / "kernel-metadata.json").write_text(json.dumps(metadata, indent=2) + "\n")
    manifest = {
        "experiment": "v32_omnipose_g2", "status": "STAGED_NOT_LAUNCHED",
        "source_sha256": source_hash, "kernel_sha256": sha256(code_file),
        "annotation_sha256": ANNOTATION_SHA256, "upstream_commit": UPSTREAM_COMMIT,
        "upstream_core_sha256": UPSTREAM_CORE_SHA256,
        "backbone_url": BACKBONE_URL, "backbone_sha256": BACKBONE_SHA256,
        "packages": list(PACKAGES), "max_steps": MAX_STEPS, "target_pq": 0.85,
        "memory_gate_mib": 14336, "records": 16, "samples": 144,
        "reads_tune": False, "reads_audit": False, "reads_test": False,
        "exports": False, "submits": False,
    }
    (output / "staging_manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    return output


def main() -> None:
    root = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=root / "outputs/v32_g2_kaggle")
    args = parser.parse_args()
    print(stage(root, args.output))


if __name__ == "__main__":
    main()
